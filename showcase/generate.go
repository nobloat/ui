// Generate writes everything made from the Go values in root (the ui repo): the specimens into the design system pages,
// fragments/, sample/ with its bundle, components.js, nb.html-data.json and ui.types.js. With update false it changes
// nothing and returns the stale files.
func Generate(root string, update bool) ([]string, error) {
	want := map[string][]byte{}
	spec := map[string]string{}
	for name, n := range Specimens {
		var b bytes.Buffer
		if err := n.Render(ui.NewCtx("en", nil), &b); err != nil {
			return nil, fmt.Errorf("specimen %s: %w", name, err)
		}
		spec[name] = b.String()
		want["fragments/"+name+".html"] = append(b.Bytes(), '\n')
	}
	for _, page := range []string{"components.html", "blocks.html", "shell.html"} {
		b, err := os.ReadFile(filepath.Join(root, page))
		if err != nil {
			return nil, err
		}
		out, err := fill(string(b), spec)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", page, err)
		}
		want[page] = []byte(out)
	}
	for dir, set := range map[string]map[string]ui.Page{"showcase/sample": Pages, "screens/auth": auth.Pages} {
		var pages []ui.Node
		for name, p := range set {
			var b bytes.Buffer
			if err := ui.Render(&b, "en", nil, p); err != nil {
				return nil, fmt.Errorf("%s/%s: %w", dir, name, err)
			}
			want[dir+"/"+name+".html"] = b.Bytes()
			pages = append(pages, p)
		}
		// index.html: the screens of the set, one link each
		names := mapsKeys(set)
		slices.Sort(names)
		var rows ui.Rows
		for _, n := range names {
			rows = append(rows, ui.Row{Href: n + ".html", Label: n, Meta: string(set[n].Title)})
		}
		index := ui.Page{Title: ui.Text(dir), App: "nobloat/ui", Static: "./", Main: rows}
		var b bytes.Buffer
		if err := ui.Render(&b, "en", nil, index); err != nil {
			return nil, err
		}
		want[dir+"/index.html"] = b.Bytes()
		css, js, err := ui.Assets(append(pages, index)...)
		if err != nil {
			return nil, err
		}
		want[dir+"/ui.css"], want[dir+"/ui.js"] = css, js
	}
	var err error
	if want["components.js"], err = allJS(root); err != nil {
		return nil, err
	}
	types, data, err := typesAndData(root)
	if err != nil {
		return nil, err
	}
	want["ui.types.js"], want["nb.html-data.json"] = types, data

	var stale []string
	for path, b := range want {
		full := filepath.Join(root, path)
		if old, _ := os.ReadFile(full); bytes.Equal(old, b) {
			continue
		}
		stale = append(stale, path)
		if update {
			os.MkdirAll(filepath.Dir(full), 0o755)
			if err := os.WriteFile(full, b, 0o644); err != nil {
				return nil, err
			}
		}
	}
	// fragments of specimens that no longer exist
	old, _ := filepath.Glob(filepath.Join(root, "fragments", "*.html"))
	for _, f := range old {
		if _, ok := want["fragments/"+filepath.Base(f)]; !ok {
			stale = append(stale, "fragments/"+filepath.Base(f))
			if update {
				os.Remove(f)
			}
		}
	}
	sort.Strings(stale)
	return stale, nil
}

var (
	region  = regexp.MustCompile(`(?s)<!--spec:([\w-]+)-->.*?<!--/spec-->`)
	copyBtn = regexp.MustCompile(`data-spec="([\w-]+)" data-copy="[^"]*"`)
)

// fill: <!--spec:x-->…<!--/spec--> gets the specimen's markup, a copy button with data-spec="x" its markup to copy.
func fill(page string, spec map[string]string) (string, error) {
	var missing []string
	get := func(name string) string {
		s, ok := spec[name]
		if !ok {
			missing = append(missing, name)
		}
		return s
	}
	page = region.ReplaceAllStringFunc(page, func(m string) string {
		name := region.FindStringSubmatch(m)[1]
		return "<!--spec:" + name + "-->" + get(name) + "<!--/spec-->"
	})
	page = copyBtn.ReplaceAllStringFunc(page, func(m string) string {
		name := copyBtn.FindStringSubmatch(m)[1]
		return `data-spec="` + name + `" data-copy="` + html.EscapeString(get(name)) + `"`
	})
	if len(missing) > 0 {
		return "", fmt.Errorf("no specimen %s", strings.Join(missing, ", "))
	}
	return page, nil
}

// allJS: the design system pages load every part's script: token/base.js, then the levels in order.
func allJS(root string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// nobloat/ui: every part's script for the design system pages, generated by nbui gen: do not edit.\n")
	for _, dir := range []string{"token", "components", "blocks", "shell"} {
		var files []string
		filepath.WalkDir(filepath.Join(root, dir), func(p string, d fs.DirEntry, err error) error {
			if err == nil && strings.HasSuffix(p, ".js") {
				files = append(files, p)
			}
			return nil
		})
		slices.Sort(files)
		for _, f := range files {
			src, err := os.ReadFile(f)
			if err != nil {
				return nil, err
			}
			rel, _ := filepath.Rel(root, f)
			fmt.Fprintf(&b, "\n// %s\n%s", filepath.ToSlash(rel), src)
		}
	}
	return b.Bytes(), nil
}

// typesAndData: JSDoc typedefs of every exported struct of package ui, and VS Code's custom HTML data for its custom
// elements (ui.Elements), with the doc comments as descriptions.
func typesAndData(root string) (types, data []byte, err error) {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, root, func(fi fs.FileInfo) bool { return !strings.HasSuffix(fi.Name(), "_test.go") }, parser.ParseComments)
	if err != nil {
		return nil, nil, err
	}
	d := doc.New(pkgs["ui"], "github.com/nobloat/ui", 0)
	var t strings.Builder
	t.WriteString("// nobloat/ui: the typed UI for editors (JSDoc, checked with // @ts-check), generated by nbui gen from the Go types: do not edit.\n")
	t.WriteString("// Only types: the markup comes from the Go renderer, or from fragments/ for apps not in Go.\n\n/** @typedef {Object<string, any>} Node any part */\n")
	icons := make([]string, 0, len(ui.IconNames))
	for _, n := range ui.IconNames {
		icons = append(icons, fmt.Sprintf("%q", n))
	}
	fmt.Fprintf(&t, "/** @typedef {%s} Icon */\n", strings.Join(icons, "|"))
	fields := map[string][]*ast.Field{}
	for _, typ := range d.Types {
		ts := typ.Decl.Specs[0].(*ast.TypeSpec)
		desc := oneLine(typ.Doc)
		switch x := ts.Type.(type) {
		case *ast.StructType:
			fields[typ.Name] = x.Fields.List
			fmt.Fprintf(&t, "\n/**\n * %s\n * @typedef {Object} %s\n", desc, typ.Name)
			for _, f := range x.Fields.List {
				for _, n := range f.Names {
					if n.IsExported() {
						fmt.Fprintf(&t, " * @property {%s} [%s]%s\n", jsType(f.Type), n.Name, comment(f))
					}
				}
			}
			t.WriteString(" */\n")
		case *ast.Ident, *ast.ArrayType:
			if typ.Name != "Icon" {
				fmt.Fprintf(&t, "/** @typedef {%s} %s %s */\n", jsType(ts.Type), typ.Name, desc)
			}
		}
	}
	type attr struct {
		Name        string `json:"name"`
		Description string `json:"description,omitempty"`
	}
	type tag struct {
		Name        string `json:"name"`
		Description string `json:"description"`
		Attributes  []attr `json:"attributes"`
	}
	var tags []tag
	els := mapsKeys(ui.Elements)
	slices.Sort(els)
	for _, el := range els {
		typ := reflect.TypeOf(ui.Elements[el])
		tg := tag{Name: el, Description: oneLine(docOf(d, typ.Name()))}
		for _, f := range fields[typ.Name()] {
			for _, n := range f.Names {
				sf, _ := typ.FieldByName(n.Name)
				if a := sf.Tag.Get("attr"); a != "" {
					tg.Attributes = append(tg.Attributes, attr{a, strings.TrimPrefix(comment(f), " - ")})
				}
			}
		}
		tags = append(tags, tg)
	}
	data, err = json.MarshalIndent(struct {
		Version float64 `json:"version"`
		Tags    []tag   `json:"tags"`
	}{1.1, tags}, "", "  ")
	return []byte(t.String()), append(data, '\n'), err
}

func mapsKeys[V any](m map[string]V) []string {
	var ks []string
	for k := range m {
		ks = append(ks, k)
	}
	return ks
}

func docOf(d *doc.Package, name string) string {
	for _, t := range d.Types {
		if t.Name == name {
			return t.Doc
		}
	}
	return ""
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

func comment(f *ast.Field) string {
	c := f.Comment.Text()
	if c == "" {
		c = f.Doc.Text()
	}
	if c = oneLine(c); c != "" {
		return " - " + c
	}
	return ""
}

func jsType(e ast.Expr) string {
	switch x := e.(type) {
	case *ast.Ident:
		switch x.Name {
		case "string", "Text", "State", "FieldType":
			return "string"
		case "bool":
			return "boolean"
		case "int", "float64":
			return "number"
		}
		return x.Name
	case *ast.StarExpr:
		return jsType(x.X)
	case *ast.ArrayType:
		return jsType(x.Elt) + "[]"
	}
	return "any"
}
